"""Puertos (interfaces) que el grafo necesita; la infraestructura los implementa."""
from datetime import datetime
from typing import Any, AsyncContextManager, Callable, Optional, Protocol


class CalendarPort(Protocol):
    """Subconjunto de CalendarService que usa el agente."""

    async def check_availability(self, start_at: datetime, end_at: datetime) -> bool: ...
    async def create_event(self, appointment_data: Any, end_at: datetime,
                           service_name: str = "", customer_name: str = "") -> Optional[str]: ...
    async def delete_event(self, google_event_id: str) -> bool: ...


CalendarFactory = Callable[[dict], CalendarPort]


class CitasTx(Protocol):
    """Operaciones dentro de una transacción. Todas filtran por workspace_id."""

    async def get_service(self, workspace_id: str, service_id: str) -> Optional[dict]: ...
    async def get_calendar(self, workspace_id: str, calendar_id: str) -> Optional[dict]: ...
    async def list_calendars(self, workspace_id: str) -> list[dict]: ...
    async def lock_calendar(self, calendar_id: str) -> None: ...
    async def has_conflict(self, calendar_id: str, start_at: datetime, end_at: datetime) -> bool: ...
    async def busy_slots(self, calendar_id: str, start_at: datetime, end_at: datetime) -> list[tuple[datetime, datetime]]: ...
    async def get_customer_name(self, workspace_id: str, customer_id: str) -> str: ...
    async def insert_appointment(self, *, workspace_id: str, customer_id: str, channel_id: str,
                                 service: dict, calendar_id: str,
                                 start_at: datetime, end_at: datetime) -> str: ...
    async def set_google_event_id(self, appointment_id: str, google_event_id: str) -> None: ...
    async def get_cancellable(self, workspace_id: str, customer_id: str, appointment_id: str) -> Optional[dict]: ...
    async def mark_cancelled(self, appointment_id: str) -> None: ...


class CitasRepository(Protocol):
    """Acceso a datos. `transaction()` hace commit al salir limpio y rollback si lanza."""

    def transaction(self) -> AsyncContextManager[CitasTx]: ...
    async def record_tool_call(self, agent_run_id: str, tool_name: str, tool_input: dict,
                               tool_output: dict, ok: bool) -> None: ...
    async def recent_messages(self, workspace_id: str, conversation_id: str, limit: int = 10) -> list[dict]: ...
